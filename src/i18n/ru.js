/** Russian plural form: 1 год, 2 года, 5 лет, 11 лет, 21 год. */
export function pluralize(value, forms) {
  const { one, few, many } = forms;
  const abs = Math.abs(value) % 100;
  if (abs >= 11 && abs <= 14) {
    return many;
  }

  const mod = abs % 10;
  if (mod === 1) {
    return one;
  }
  if (mod >= 2 && mod <= 4) {
    return few;
  }
  return many;
}

